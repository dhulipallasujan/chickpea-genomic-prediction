# Build the results tables and figures from the saved summaries, and write the
# tables into the README between the RESULTS markers so numbers never drift.
if (!requireNamespace("ggplot2", quietly = TRUE)) install.packages("ggplot2", repos = "https://cloud.r-project.org")
if (!requireNamespace("ggplot2", quietly = TRUE)) stop("Install ggplot2 to draw the figures.")
library(ggplot2)
dir.create("figures", showWarnings = FALSE)

repeats <- read.csv("reports/multienvironment_validation_repeats.csv", stringsAsFactors = FALSE)
loyo <- read.csv("reports/leave_one_season_out.csv", stringsAsFactors = FALSE)
density <- read.csv("reports/marker_density_sensitivity.csv", stringsAsFactors = FALSE)
qc <- read.csv("reports/multienvironment_qc.csv", stringsAsFactors = FALSE)

short_scenario <- function(x) ifelse(grepl("^CV2", x), "CV2: known lines", "CV1: new genetic clusters")
fmt <- function(x, d = 1) formatC(x, format = "f", digits = d)

# RMSE reduction versus the environment mean, computed within each repeat.
base <- repeats[repeats$model == "Environment mean", c("scenario", "repeat_id", "environment", "rmse")]
names(base)[4] <- "rmse_env_mean"
rep2 <- merge(repeats[repeats$model != "Environment mean", ], base, by = c("scenario", "repeat_id", "environment"))
rep2$reduction_pct <- 100 * (1 - rep2$rmse / rep2$rmse_env_mean)
key <- paste(rep2$scenario, rep2$environment, rep2$model, sep = "|")
agg <- do.call(rbind, lapply(split(rep2, key), function(d) data.frame(
  scenario = d$scenario[1], environment = d$environment[1], model = d$model[1],
  rmse = mean(d$rmse), rmse_env_mean = mean(d$rmse_env_mean),
  reduction_mean = mean(d$reduction_pct), reduction_sd = stats::sd(d$reduction_pct),
  pearson_r = mean(d$pearson_r), stringsAsFactors = FALSE)))
rownames(agg) <- NULL
agg$scenario_short <- short_scenario(agg$scenario)
model_order <- c("Marker main effects", "Marker main + GxE", "Known-line phenotype + environment shift")
agg <- agg[order(agg$scenario_short, agg$environment, match(agg$model, model_order)), ]

cv_lines <- c("| Scenario | Season | Model | RMSE | Environment-mean RMSE | RMSE reduction vs environment mean (± SD) | Pearson r |",
              "|---|---|---|---:|---:|---:|---:|")
for (i in seq_len(nrow(agg))) {
  cv_lines <- c(cv_lines, paste0("| ", agg$scenario_short[i], " | ", agg$environment[i], " | ", agg$model[i],
    " | ", fmt(agg$rmse[i]), " | ", fmt(agg$rmse_env_mean[i]), " | ", fmt(agg$reduction_mean[i]), "% ± ",
    fmt(agg$reduction_sd[i]), " | ", fmt(agg$pearson_r[i], 3), " |"))
}
loyo_lines <- c("| Direction | Training-season mean RMSE | Marker main RMSE | Reduction | Pearson r | Selected penalty |",
                "|---|---:|---:|---:|---:|---:|")
for (d in unique(loyo$direction)) {
  z <- loyo[loyo$direction == d, ]
  b <- z$rmse[z$model == "Training-season mean"]
  m <- z[z$model == "Marker main effects", ]
  loyo_lines <- c(loyo_lines, paste0("| ", d, " | ", fmt(b), " | ", fmt(m$rmse), " | ", fmt(100 * (1 - m$rmse / b)),
    "% | ", fmt(m$pearson_r, 3), " | ", m$selected_lambda, " |"))
}
dens_lines <- c("| Season | Markers | RMSE (± SD) | Pearson r |", "|---|---:|---:|---:|")
for (i in order(density$environment, density$marker_count)) {
  dens_lines <- c(dens_lines, paste0("| ", density$environment[i], " | ", density$marker_count[i], " | ",
    fmt(density$rmse_mean[i]), " ± ", fmt(density$rmse_sd[i]), " | ", fmt(density$pearson_r_mean[i], 3), " |"))
}
diag_lines <- character()
if ("season_to_season_pearson" %in% names(qc)) {
  diag_lines <- c(diag_lines, paste0("- Season-to-season Pearson correlation of grain yield (paired accessions): **",
    fmt(qc$season_to_season_pearson[1], 3), "**."))
}
if ("lambda_edge_share_cv" %in% names(qc)) {
  diag_lines <- c(diag_lines, paste0("- Share of tuned ridge penalties at an edge of the grid (1 to 1e5): CV **",
    fmt(100 * qc$lambda_edge_share_cv[1], 0), "%**, marker-density runs **",
    fmt(100 * qc$lambda_edge_share_density[1], 0), "%**. A high share means the grid is too narrow."))
}

block <- c("", "**Cross-validation (repeated 5-fold, 10 repeats).** Positive reduction means better than predicting the training-environment mean. The known-line baseline uses the accession's other-season phenotype plus an environment shift.", "",
           cv_lines, "", "**Leave-one-season-out (same location, two years).**", "", loyo_lines, "",
           "**Marker-density sensitivity (grouped CV1, 3 repeats).**", "", dens_lines, "", diag_lines, "")
writeLines(c("# Results tables (generated by R/08_figures_and_tables.R)", block), "reports/results_table.md")

readme <- "README.md"
if (file.exists(readme)) {
  txt <- readLines(readme, warn = FALSE)
  s <- grep("<!-- RESULTS:START -->", txt, fixed = TRUE)
  e <- grep("<!-- RESULTS:END -->", txt, fixed = TRUE)
  if (length(s) == 1L && length(e) == 1L && e > s) {
    writeLines(c(txt[seq_len(s)], block, txt[e:length(txt)]), readme)
  } else warning("README RESULTS markers not found; only reports/results_table.md was written.")
}

cols <- c("Marker main effects" = "#2D6A8A", "Marker main + GxE" = "#D55E00",
          "Known-line phenotype + environment shift" = "#8C8C8C")
p <- ggplot(agg, aes(x = environment, y = reduction_mean, fill = model)) +
  geom_col(position = position_dodge(width = 0.8), width = 0.7) +
  geom_errorbar(aes(ymin = reduction_mean - reduction_sd, ymax = reduction_mean + reduction_sd),
                position = position_dodge(width = 0.8), width = 0.2) +
  geom_hline(yintercept = 0, linewidth = 0.4) +
  facet_wrap(~ scenario_short) +
  scale_fill_manual(values = cols) +
  labs(title = "Grain-yield prediction: RMSE reduction versus the environment mean",
       subtitle = "ICRISAT CicerSeq, two seasons at one location; below zero is worse than the mean",
       x = NULL, y = "RMSE reduction (%)", fill = NULL,
       caption = "Error bars: SD across repeated splits, not a population confidence interval.") +
  guides(fill = guide_legend(nrow = 2)) +
  theme_minimal(base_size = 12) +
  theme(legend.position = "bottom", plot.title = element_text(face = "bold"))
ggsave("figures/validation_summary.png", p, width = 9.5, height = 5.8, dpi = 150)

density$panel <- factor(density$marker_count)
p2 <- ggplot(density, aes(x = panel, y = rmse_mean)) +
  geom_point(size = 3, colour = "#2D6A8A") +
  geom_errorbar(aes(ymin = rmse_mean - rmse_sd, ymax = rmse_mean + rmse_sd), width = 0.15, colour = "#2D6A8A") +
  facet_wrap(~ environment, scales = "free_y") +
  labs(title = "Marker-density sensitivity (grouped CV1)", x = "Number of markers", y = "RMSE (source GY scale)",
       caption = "Error bars: SD across 3 repeated splits.") +
  theme_minimal(base_size = 12) + theme(plot.title = element_text(face = "bold"))
ggsave("figures/marker_density.png", p2, width = 8, height = 4.2, dpi = 150)
cat("Wrote reports/results_table.md, figures/validation_summary.png, figures/marker_density.png\n")
